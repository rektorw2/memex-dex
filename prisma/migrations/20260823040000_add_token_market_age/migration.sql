-- Возраст рынка отдельно от возраста нашей записи.
--
-- Список «Новые» строился по `Token.createdAt` — времени импорта.
-- Старый токен, впервые увиденный сегодня, попадал в новинки,
-- а на новизну на этом рынке покупают.
--
-- Обе колонки необязательные и без умолчания. Умолчание `now()`
-- здесь было бы худшим вариантом: оно объявило бы все существующие
-- записи созданными в момент миграции, то есть выдало бы полторы
-- тысячи старых токенов за новые разом.
--
-- Миграция только добавляет. Ни одного DROP, ни одного изменения
-- типа, ни одной записи данных.

ALTER TABLE "Token" ADD COLUMN "poolCreatedAt" TIMESTAMP(3);
ALTER TABLE "Token" ADD COLUMN "firstSeenAt" TIMESTAMP(3);

-- Индексы под сортировку и отсечку по возрасту: без них «Новые»
-- превращаются в полный проход по таблице.
CREATE INDEX "Token_isHidden_poolCreatedAt_idx" ON "Token"("isHidden", "poolCreatedAt");
CREATE INDEX "Token_isHidden_firstSeenAt_idx" ON "Token"("isHidden", "firstSeenAt");
