-- Контракт сводки результативности кошелька.
--
-- Только добавление. Ни одна существующая колонка не меняется,
-- не переименовывается и не удаляется; ни одна строка не удаляется.
--
-- ─── Зачем ──────────────────────────────────────────────────────────
--
-- База хранила только победы, крупные победы, rug и число купленных
-- токенов. Знаменатель доли попаданий не хранился вовсе, и чтение
-- восстанавливало его выражением `max(wins2x, rugs)`.
--
-- Это теряет данные. Исход между 0.2x и 2x оцениваемый, но не победа
-- и не rug — в `max` он не входит. Десять оценённых токенов, из них
-- одна победа, один rug и восемь обычных, давали знаменатель 1
-- и долю попаданий 100% вместо 10%.
--
-- Восстановить знаменатель из победителей нельзя в принципе: победы
-- являются подмножеством, а подмножество не определяет множество.
-- Поэтому знаменатель и разбиение исходов теперь хранятся.
--
-- ─── Почему все колонки NULL-able ───────────────────────────────────
--
-- NULL здесь — не «ноль», а «этот кошелёк ещё не пересчитан новыми
-- правилами». Умолчание `0` стёрло бы это различие: строка со старым
-- Smart Score 100 выглядела бы как честно посчитанная строка с нулём
-- оцениваемых исходов, и отличить одну от другой было бы нечем.
--
-- Пока `scoreVersion` пуст, чтение обязано отдавать `score = null`
-- и состояние «ожидает пересчёта», а не показывать старые числа
-- как исправленные.

