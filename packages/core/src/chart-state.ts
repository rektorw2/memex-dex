/**
 * Почему графика нет.
 *
 * Раньше на все случаи было одно сообщение — «не найден пул
 * ликвидности», — и оно врало чаще, чем говорило правду: его видели
 * у токена с пулом на 184 тысячи долларов, потому что пул был,
 * а свечей не было. Человек читал это как «токен мёртвый»
 * и уходил.
 *
 * Причины разные, и действия по ним разные: одну ждут, другую
 * не дождутся никогда, третью можно повторить. Свести их к одной
 * строке значит соврать в пяти случаях из шести.
 */

export type ChartState =
  /** Свечи есть, всё в порядке. */
  | 'ready'
  /** Пул ещё не определён импортёром. Данные появятся. */
  | 'pool-pending'
  /** Пул есть, свечи стоят в очереди на загрузку. */
  | 'candles-queued'
  /** Сеть или пул не поддерживаются провайдером свечей. Никогда не появятся. */
  | 'unsupported'
  /** Пул и свечи есть, но за выбранный период данных нет. */
  | 'empty-period'
  /** Запрос завершился ошибкой. Можно повторить. */
  | 'failed';

export interface ChartStateInput {
  /** Есть ли у токена адрес пула. */
  hasPool: boolean;
  /** Поддерживает ли провайдер свечей эту сеть. */
  supported: boolean;
  /** Сколько свечей нашлось за выбранный период. */
  candleCount: number;
  /** Есть ли у токена свечи хоть за какой-нибудь период. */
  hasAnyCandles: boolean;
  /** Запрос упал. */
  failed?: boolean;
}

/**
 * Что показать вместо графика.
 *
 * Порядок проверок — от самой определённой причины к самой общей.
 * Ошибка идёт первой: при упавшем запросе всё остальное неизвестно,
 * и объяснять отсутствие данных отсутствием пула было бы догадкой.
 */
export function chartState(input: ChartStateInput): ChartState {
  if (input.failed) return 'failed';

  if (!input.supported) return 'unsupported';
  if (!input.hasPool) return 'pool-pending';

  if (input.candleCount > 0) return 'ready';

  // Пул есть, свечи по другим интервалам есть, а по этому нет:
  // значит период пустой, а не загрузка не дошла.
  return input.hasAnyCandles ? 'empty-period' : 'candles-queued';
}

/** Текст для человека. Ни один не обещает того, чего не будет. */
export const CHART_STATE_TEXT: Readonly<Record<ChartState, string>> = {
  ready: '',
  'pool-pending': 'Пул ещё определяется — график появится после импорта',
  'candles-queued': 'История цены загружается, обычно это несколько минут',
  unsupported: 'Провайдер свечей не поддерживает эту сеть',
  'empty-period': 'За выбранный период сделок не было',
  failed: 'Не удалось загрузить историю цены',
};

/** Стоит ли предлагать повтор. Ждать очередь кнопкой бессмысленно. */
export function chartStateRetryable(state: ChartState): boolean {
  return state === 'failed';
}

/**
 * Появится ли график сам по себе.
 *
 * Отличает ожидание от тупика: `unsupported` ждать бесполезно,
 * и интерфейс не должен намекать на обратное крутящимся индикатором.
 */
export function chartStateWillResolve(state: ChartState): boolean {
  return state === 'pool-pending' || state === 'candles-queued';
}
