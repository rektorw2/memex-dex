import type { PlanCode } from './entitlements.js';

/**
 * Состояние доступа для верхней панели.
 *
 * ─── Зачем отдельная функция ────────────────────────────────────────
 *
 * Индикатор в шапке отвечает на один вопрос: что у человека сейчас
 * с доступом. Ответов шесть, и различаются они не оформлением,
 * а смыслом — предложить бесплатный период, показать остаток,
 * позвать выбрать план, назвать оплаченный тариф, отметить служебный
 * доступ, промолчать.
 *
 * Пока это жило россыпью условий внутри разметки, каждое новое
 * состояние добавляло вложенный тернарник, и проверить их все можно
 * было только глазами в браузере. Здесь они разложены один раз
 * и проверены тестами; разметка получает готовый ответ.
 *
 * ─── Чего здесь нет ─────────────────────────────────────────────────
 *
 * Ни цен, ни длительности пробного периода, ни списка возможностей.
 * Всё это уже описано один раз — в матрице прав и на странице тарифов.
 * Второй каталог рано или поздно разойдётся с первым, и человек
 * увидит в шапке обещание, которого продукт не выполняет.
 *
 * Роль тоже не участвует. Служебный доступ приходит с сервера полем
 * `serviceAccess`; выводить его из «пользователь администратор» —
 * значит завести на клиенте второй источник прав.
 */

/** Что именно показывает индикатор. */
export type AccessIndicatorVariant =
  /** Гость: индикатора нет вовсе. */
  | 'hidden'
  /**
   * Состояние ещё не известно.
   *
   * Первая загрузка либо неудачный первый запрос. Место в шапке
   * занимается, но никакого утверждения о доступе не делается:
   * мелькнувшее «Выбрать план» у человека с оплаченным тарифом —
   * это ложь, пусть и на долю секунды.
   */
  | 'pending'
  /** Пробный период ещё не использован. */
  | 'trial-offer'
  /** Пробный период идёт. */
  | 'trial-active'
  /** Пробный период израсходован, тарифа нет. */
  | 'locked'
  /** Действует оплаченный тариф. */
  | 'paid'
  /** Доступ выдан ролью. */
  | 'service';

/** Значок состояния. Имена, а не разметка: рисует их интерфейс. */
export type AccessIndicatorIcon = 'gift' | 'clock' | 'lock' | 'crown' | 'shield' | 'pending';

/**
 * Цветовая роль.
 *
 * `warn` — только для действительно закончившегося доступа. Красить
 * им пробный период значит выдавать нормальное течение времени
 * за аварию; человек привыкает к тревожному цвету и перестаёт его
 * замечать ровно к тому моменту, когда цвет становится уместен.
 */
export type AccessIndicatorTone = 'accent' | 'neutral' | 'warn';

export interface AccessIndicatorView {
  variant: AccessIndicatorVariant;
  icon: AccessIndicatorIcon;
  /** Короткая подпись для широкого экрана. Пусто — значит только значок. */
  label: string;
  /** Полное состояние словами: для `aria-label` и `title`. */
  accessibleLabel: string;
  /** Куда ведёт нажатие. `null` — никуда, элемент не кликается. */
  href: string | null;
  /** Одно предложение-пояснение. Не реклама. */
  tooltip: string;
  tone: AccessIndicatorTone;
}

/**
 * Что функция знает о человеке.
 *
 * Ровно те поля ответа `/access/me`, которые влияют на ответ.
 * Полный `AccessState` сюда не тянется намеренно: чем уже вход,
 * тем очевиднее, что решение не зависит ни от чего постороннего.
 */
export interface AccessIndicatorSnapshot {
  effectivePlan: PlanCode;
  status: 'expired' | 'trial' | 'active' | 'service';
  canStartTrial: boolean;
  emailVerified: boolean;
  serviceAccess: boolean;
  trialRemainingSeconds: number;
}

export interface AccessIndicatorInput {
  /**
   * В браузере есть токен сессии.
   *
   * Отдельно от `anonymous`, и разница здесь принципиальная.
   * `anonymous` начинается с `true` — провайдер ещё не спросил
   * сервер и честно не знает ответа. Пока эти два состояния были
   * одним, вошедший человек при первой загрузке считался гостем:
   * индикатор не рисовался, а через полсекунды появлялся и сдвигал
   * соседей в шапке.
   *
   * Токен отвечает на другой вопрос — «сессия вообще есть?» —
   * и отвечает мгновенно, ещё до сети.
   */
  hasSession: boolean;
  /**
   * Сервер сказал, что человек не авторизован.
   *
   * Значимо только после первого ответа: до него это лишь
   * начальное значение.
   */
  anonymous: boolean;
  /** Идёт самая первая загрузка: о человеке ещё ничего не известно. */
  loading: boolean;
  /**
   * Последнее известное состояние.
   *
   * При фоновой перепроверке остаётся прежним — провайдер его
   * не стирает. Поэтому отдельного правила «во время перепроверки
   * показывать старое» здесь нет: оно выполняется само, и это
   * лучше правила, которое можно забыть применить.
   */
  access: AccessIndicatorSnapshot | null;
  /**
   * Остаток пробного периода словами.
   *
   * Приходит готовым, потому что считается от секунд, присланных
   * сервером. Считать срок по часам браузера нельзя: сбитые
   * на сутки часы дают «осталось 4 дня» при закончившемся периоде,
   * и человек не понимает, почему ничего не работает.
   */
  trialRemaining?: string;
  /** Дата окончания периода словами. Только для подсказки. */
  trialUntil?: string;
}

/** Название тарифа так, как его читает человек. */
const PLAN_LABELS: Record<PlanCode, string> = {
  EXPIRED: 'Без плана',
  TRIAL: 'Trial',
  PRO: 'PRO',
  SEMI_AUTO: 'SEMI AUTO',
  FULL_AUTO: 'FULL AUTO',
};

export function planLabel(plan: PlanCode): string {
  return PLAN_LABELS[plan];
}

const HIDDEN: AccessIndicatorView = {
  variant: 'hidden',
  icon: 'pending',
  label: '',
  accessibleLabel: '',
  href: null,
  tooltip: '',
  tone: 'neutral',
};

/**
 * Состояние индикатора по ответу сервера.
 *
 * Порядок проверок — часть смысла, а не оптимизация.
 *
 * Сессии нет — нет и индикатора: у гостя в шапке уже стоят
 * «Регистрация» и «Войти».
 *
 * Дальше первая загрузка. Пока ответа не было, любое утверждение
 * о доступе — выдумка, и «Выбрать план», мелькнувшее у человека
 * с оплаченным тарифом, подрывает доверие ко всему остальному,
 * что мы о нём показываем.
 *
 * Отказ сервера идёт после загрузки: `anonymous` до первого ответа
 * означает «ещё не спрашивали», и различить эти два случая можно
 * только по `loading`.
 *
 * Служебный доступ идёт раньше тарифа: у администратора план может
 * быть каким угодно, включая `EXPIRED`, а возможности при этом
 * полные. Проверь мы сначала план — и человеку со служебным доступом
 * предлагалось бы купить то, что у него уже есть.
 */
export function accessIndicatorState(input: AccessIndicatorInput): AccessIndicatorView {
  const { access } = input;

  // Известное состояние сильнее любого признака сессии: если сервер
  // уже ответил, отвечаем по ответу.
  if (access == null) {
    if (!input.hasSession) return HIDDEN;

    /*
     * Токен есть, ответа ещё нет.
     *
     * Место под индикатор занимается, но ничего не утверждается.
     * Без этого шапка вошедшего человека дёргалась при каждой
     * загрузке страницы.
     */
    if (input.loading) {
      return {
        variant: 'pending',
        icon: 'pending',
        label: '',
        accessibleLabel: 'Проверяем доступ',
        href: null,
        tooltip: 'Проверяем состояние доступа',
        tone: 'neutral',
      };
    }

    /*
     * Ответ был, и это отказ.
     *
     * Токен в браузере остался, но сервер его не признал: сессия
     * истекла либо отозвана. Показывать состояние доступа нечему —
     * человеку нужен вход, и он уже предложен в шапке.
     */
    if (input.anonymous) return HIDDEN;

    // Ответа нет и не будет: первый запрос не удался. Придумывать
    // состояние неоткуда.
    return {
      variant: 'pending',
      icon: 'pending',
      label: '',
      accessibleLabel: 'Проверяем доступ',
      href: null,
      tooltip: 'Проверяем состояние доступа',
      tone: 'neutral',
    };
  }

  if (access.serviceAccess) {
    return {
      variant: 'service',
      icon: 'shield',
      label: 'Service',
      accessibleLabel: 'Служебный доступ',
      href: '/access',
      tooltip: 'Доступ выдан ролью, тариф не требуется',
      tone: 'neutral',
    };
  }

  if (access.status === 'active') {
    const name = planLabel(access.effectivePlan);

    return {
      variant: 'paid',
      icon: 'crown',
      label: name,
      accessibleLabel: `Тариф ${name}`,
      href: '/plans',
      tooltip: `Активен тариф ${name}`,
      tone: 'accent',
    };
  }

  if (access.effectivePlan === 'TRIAL') {
    const remaining = input.trialRemaining?.trim();
    const label = remaining ? `Trial · ${remaining}` : 'Trial';

    return {
      variant: 'trial-active',
      icon: 'clock',
      label,
      accessibleLabel: remaining
        ? `Бесплатный период, осталось ${remaining}`
        : 'Бесплатный период активен',
      href: '/plans',
      // Дата окончания — в подсказке, а не в подписи: обратный отсчёт
      // в шапке создаёт срочность, которой нет.
      tooltip: input.trialUntil
        ? `Бесплатный период до ${input.trialUntil}`
        : 'Бесплатный период активен',
      tone: 'accent',
    };
  }

  if (access.canStartTrial) {
    return {
      variant: 'trial-offer',
      icon: 'gift',
      label: 'Бесплатный доступ',
      accessibleLabel: 'Доступен бесплатный период',
      /*
       * Ведёт на страницу состояния, а не включает период.
       *
       * Включение требует подтверждённой почты и явного выбора,
       * и то и другое уже описано на своём месте. Кнопка в шапке,
       * молча тратящая единственный пробный период, — это решение
       * за человека, принятое случайным нажатием.
       */
      href: '/access',
      tooltip: access.emailVerified
        ? 'Бесплатный период ещё не использован'
        : 'Бесплатный период ещё не использован, потребуется подтвердить почту',
      tone: 'accent',
    };
  }

  return {
    variant: 'locked',
    icon: 'lock',
    label: 'Выбрать план',
    accessibleLabel: 'Доступ закрыт, выберите план',
    href: '/plans',
    tooltip: 'Бесплатный период использован',
    tone: 'warn',
  };
}

/** Показывается ли индикатор вообще. */
export function accessIndicatorVisible(view: AccessIndicatorView): boolean {
  return view.variant !== 'hidden';
}
