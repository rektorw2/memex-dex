/**
 * Почему экран агента не открылся — четыре разных ответа.
 *
 * До этого их был один. Любая неудача — истёкшая сессия, отсутствие
 * подписки, упавший сервер, оборванная сеть — приводила к одной
 * карточке «Агент временно недоступен. Обновите страницу через
 * несколько секунд».
 *
 * Каждое из этих слов было неверным ровно в трёх случаях из четырёх:
 *
 *   • при истёкшей сессии обновление страницы не поможет никогда,
 *     нужно войти заново;
 *   • при отсутствии подписки — тем более: ждать нечего, доступа нет;
 *   • при обрыве сети чинить нужно не нам;
 *
 * и только при отказе сервера совет был по делу. Человек, которому
 * трижды посоветовали подождать вместо того, чтобы сказать «войдите»,
 * ждёт — и уходит.
 *
 * Здесь только правило разбора. Тексты живут в интерфейсе, коды
 * ответа приходят из адаптера.
 */

export type AgentFailureKind =
  /** Сессия истекла или её не было. Помогает вход, а не ожидание. */
  | 'SIGN_IN_REQUIRED'
  /** Вошёл, но доступа к экрану нет. Ожидание не поможет. */
  | 'ACCESS_REQUIRED'
  /** Сервер не смог собрать ответ. Повтор осмыслен. */
  | 'SERVER_UNAVAILABLE'
  /** До сервера не дошло. Повтор осмыслен, но причина не у нас. */
  | 'NETWORK_UNAVAILABLE';

export interface AgentFailureInput {
  /**
   * Код ответа HTTP, если ответ вообще был.
   *
   * `null` означает, что ответа не было: обрыв, таймаут, отказ
   * браузера. Это не то же самое, что ответ с кодом ошибки, и
   * различие здесь принципиально — во втором случае сервер жив.
   */
  status: number | null;
}

export interface AgentFailureVerdict {
  kind: AgentFailureKind;
  /** Имеет ли смысл предлагать повтор. */
  retryable: boolean;
}

export function agentFailureVerdict(input: AgentFailureInput): AgentFailureVerdict {
  if (input.status == null) return { kind: 'NETWORK_UNAVAILABLE', retryable: true };
  if (input.status === 401) return { kind: 'SIGN_IN_REQUIRED', retryable: false };
  if (input.status === 403) return { kind: 'ACCESS_REQUIRED', retryable: false };

  /*
   * Всё остальное — отказ сервера, включая неожиданные коды.
   *
   * Fail-closed наоборот: неизвестный код нельзя объявить проблемой
   * человека. Сказать «войдите» тому, чья сессия в порядке, — это
   * отправить его совершать бессмысленные действия и решить, что
   * сломался он.
   */
  return { kind: 'SERVER_UNAVAILABLE', retryable: true };
}
