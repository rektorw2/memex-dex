/**
 * События журнала капитала PAPER-счёта.
 *
 * Список закрытый и существует ради одного различия, которое легко
 * потерять: **никакого внесения средств в бумажном режиме не бывает**.
 *
 * Счёт создаётся с виртуальным капиталом, который назначил
 * администратор. Человек ничего не вносил, ничем не рисковал и ничего
 * не может вывести. Поэтому событие называется `INITIALIZE`, а не
 * `DEPOSIT`: второе слово описывает поступление чужих денег, и в
 * интерфейсе, где рядом готовится приём настоящих депозитов, разница
 * между «вам начислили виртуальную тысячу» и «вы внесли тысячу» —
 * не оттенок формулировки.
 *
 * Тесты стенда сначала ожидали `DEPOSIT`, потому что так было принято
 * писать в других частях проекта. Правильным оказалось production:
 * менять его под тест было бы ровно тем случаем, когда проверка
 * портит продукт.
 */

export const PAPER_LEDGER_EVENTS = ['INITIALIZE', 'OPEN', 'CLOSE', 'RESET'] as const;

export type PaperLedgerEvent = (typeof PAPER_LEDGER_EVENTS)[number];

export function isPaperLedgerEvent(value: unknown): value is PaperLedgerEvent {
  return typeof value === 'string' && (PAPER_LEDGER_EVENTS as readonly string[]).includes(value);
}

/**
 * Означает ли событие поступление настоящих средств.
 *
 * Всегда `false`, и это не заглушка: в бумажном контуре настоящих
 * поступлений не существует. Функция нужна, чтобы утверждение можно
 * было проверить тестом, а не держать в комментарии, — и чтобы
 * попытка завести здесь «настоящий депозит» упиралась в явный отказ,
 * а не проходила незамеченной.
 */
export function isRealDepositEvent(_event: PaperLedgerEvent): boolean {
  return false;
}

/**
 * Слово, которым нельзя называть события бумажного журнала.
 *
 * Проверяется контрактом: ни один тип события и ни одна подпись в
 * интерфейсе не имеют права утверждать, что человек что-то вносил.
 */
export const FORBIDDEN_PAPER_LEDGER_WORD = 'DEPOSIT';
