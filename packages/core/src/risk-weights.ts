/**
 * Веса кодов причин.
 *
 * Раньше числа стояли прямо в проверке, россыпью по тысяче строк.
 * Из-за этого нельзя было ответить на единственный вопрос, который
 * про них имеет смысл задавать: складываются ли они во что-то
 * осмысленное. Ответ оказался отрицательным.
 *
 * ─── Что вес означает ───────────────────────────────────────────────
 *
 * Вес отвечает на вопрос «насколько это необычно для мем-коина»,
 * а не «насколько это далеко от голубой фишки». Порог `lowRiskMaxScore`
 * равен 30, и читать его следует так: до тридцати — токен ведёт себя
 * как обычный представитель этого рынка.
 *
 * ─── Почему пришлось пересчитывать ──────────────────────────────────
 *
 * Веса калибровались в версии правил 4. Версии 5–8 добавили OKX
 * advanced-info, Honeypot.is, RugCheck, реестр RWA и с ними полтора
 * десятка новых кодов — а порог остался прежним. Сумма выросла,
 * граница не сдвинулась, и фильтр «Проверенные» опустел.
 *
 * Замер на настоящем `assessRisk` показал, насколько:
 *
 *   эмиссия не отозвана (25) + LP не залочен (15) = 40 → medium
 *
 * Это не описание подозрительного токена. Это описание обычного
 * мем-коина на Solana: большинство живых проектов не отзывают эмиссию
 * и не лочат ликвидность. Два свойства, которые есть у половины рынка,
 * выбирали 133% бюджета «низкого риска» и выбрасывали токен
 * из строгого режима.
 *
 * ─── Как пересчитаны ────────────────────────────────────────────────
 *
 * Понижены ровно те коды, которые описывают норму рынка, и ровно
 * настолько, чтобы три таких свойства вместе ещё умещались в «низкий
 * риск», а любая настоящая находка сверх них выводила из него.
 *
 * Пороги не тронуты, критические коды не тронуты, ни один код
 * не выведен из блокирующих. Это не ослабление правил: токен
 * с заблокированной продажей как блокировался, так и блокируется.
 *
 * ─── Чего этот файл не знает ────────────────────────────────────────
 *
 * Насколько повсеместно каждое свойство на самом деле. Оценки ниже —
 * суждение о рынке, а не измерение: боевой базы у меня нет. Измерить
 * можно диагностикой `checker:diagnose`, которая считает
 * распространённость каждого кода по витрине. Если замер разойдётся
 * с оценкой, править надо этот файл, а не порог.
 */

