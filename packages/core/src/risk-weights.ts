/**
 * Насколько свойство распространено на этом рынке.
 *
 * Хранится рядом с весом намеренно: вес без этой оценки выглядит
 * произволом, и через полгода его либо не тронут вовсе, либо изменят
 * наугад — ровно это с ним и произошло.
 */
export type Prevalence =
  /** Есть у большинства живых токенов. Норма рынка. */
  | 'обычное'
  /** Встречается часто, но не у большинства. */
  | 'частое'
  /** Заметное отклонение. */
  | 'редкое';

export interface WeightEntry {
  weight: number;
  prevalence: Prevalence;
  /** Почему вес именно такой. */
  why: string;
}

