/**
 * Правила синхронизации избранного.
 *
 * ─── Почему они здесь, а не в компоненте ────────────────────────────
 *
 * Всё, что решает, «что означает этот отказ» и «какие звёзды показать
 * при сбое», — это правила, а не разметка. Пока они жили внутри
 * провайдера React, проверить их можно было только запустив браузер,
 * а значит на практике не проверял никто. Ровно поэтому `catch`
 * годами превращал вошедшего человека в гостя, и заметить это удалось
 * только по скриншоту живой страницы.
 *
 * Здесь они обычные функции без React, и у них есть тесты.
 */

/** Состояние синхронизации с сервером. */
export type FavoritesSync =
  /** Ещё не спрашивали: гость либо первая загрузка. */
  | 'idle'
  /** Запрос в пути. */
  | 'loading'
  /** Список получен с сервера. */
  | 'ready'
  /**
   * Сеть или сервер: таймаут, обрыв, 500, холодный старт Render.
   * Само пройдёт — повтор с нарастающей паузой имеет смысл.
   */
  | 'unavailable'
  /**
   * 401. Сессия истекла: сервер работает и отвечает по существу.
   * Повторять бесполезно, нужен новый вход.
   */
  | 'expired'
  /**
   * 403. Сервер узнал человека и отказал: раздел не входит в тариф.
   * Повторять бесполезно и назойливо.
   */
  | 'forbidden'
  /**
   * 503. Схема базы ещё не обновлена — сервер не умеет хранить
   * отметки вовсе. Отказ администратора, а не сбой.
   */
  | 'schema-missing';

/**
 * Во что превращается отказ.
 *
 * `null` означает, что ответа не было вовсе: обрыв, таймаут,
 * отключённая сеть.
 *
 * Различать коды обязательно, потому что от них зависит поведение:
 * повторять или нет и что сказать человеку. Прежде всё сводилось
 * к одному «сервер недоступен», и человеку с истёкшей сессией
 * предлагалось подождать — совет, который никогда не сработает.
 */
export function favoritesSyncOf(status: number | null | undefined): FavoritesSync {
  if (status === 401) return 'expired';
  if (status === 403) return 'forbidden';
  if (status === 503) return 'schema-missing';

  // Неизвестный код считается временным: сетевой сбой выглядит
  // именно так, а лишний повтор дешевле молчаливой потери связи.
  return 'unavailable';
}

/** Стоит ли повторять запрос сам по себе. */
export function favoritesRetryable(sync: FavoritesSync): boolean {
  return sync === 'unavailable';
}

/**
 * Паузы между повторами, миллисекунды.
 *
 * Список конечен намеренно. Бесконечный повтор с постоянным
 * интервалом превращает один недоступный сервер в поток запросов
 * от каждой открытой вкладки; после последней паузы остаётся кнопка,
 * и решение принимает человек.
 *
 * Первая пауза заметно больше нуля: холодный старт Render занимает
 * десятки секунд, и частые попытки в это время бесполезны.
 */
export const FAVORITES_RETRY_DELAYS_MS = [2_000, 5_000, 15_000, 30_000, 60_000] as const;

/** Пауза перед попыткой номер `attempt`, считая с нуля. `null` — хватит. */
export function favoritesRetryDelay(attempt: number): number | null {
  return FAVORITES_RETRY_DELAYS_MS[attempt] ?? null;
}

/**
 * Какие отметки показывать.
 *
 * Главное правило: сбой синхронизации ничего не гасит. Прежде при
 * сбое ставилось `setKeys(new Set(guestKeys))` — то есть уже
 * показанные серверные звёзды заменялись гостевым набором и исчезали
 * с экрана, хотя на сервере никуда не делись. Для человека это
 * неотличимо от потери данных.
 *
 * Поэтому наборы объединяются, а не замещают друг друга. Отметка
 * есть, если она есть хоть где-то: локальная ещё не доехала
 * до сервера, серверная ещё не доехала до этого браузера, и обе
 * настоящие.
 */
export function visibleFavoriteKeys(input: {
  serverKeys: Iterable<string>;
  guestKeys: Iterable<string>;
}): Set<string> {
  return new Set([...input.serverKeys, ...input.guestKeys]);
}

/**
 * Нужен ли перенос гостевых отметок в аккаунт.
 *
 * Ровно один раз: повторные загрузки — после сбоя, после возврата
 * вкладки, после нажатия кнопки — ждут первый перенос, а не
 * отправляют свой. Сам перенос идемпотентен на сервере, но десять
 * одинаковых запросов подряд от одной страницы остаются дефектом,
 * даже если сервер их переживёт.
 */
export function shouldMergeGuestFavorites(input: {
  hasSession: boolean;
  guestCount: number;
  mergeInFlight: boolean;
}): boolean {
  return input.hasSession && input.guestCount > 0 && !input.mergeInFlight;
}

/**
 * Можно ли очистить локальное хранилище.
 *
 * Только после подтверждённого успеха. Очистка до ответа при обрыве
 * связи потеряла бы отметки безвозвратно: на сервер они не доехали,
 * а в браузере их уже нет.
 */
export function mayClearGuestFavorites(mergeConfirmed: boolean): boolean {
  return mergeConfirmed;
}
