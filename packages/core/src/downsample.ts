/**
 * Прореживание ряда точек до числа, которое имеет смысл рисовать.
 *
 * Причина существования арифметическая. Лента радара показывает
 * шестьдесят находок, у каждой сохраняется до сорока восьми точек
 * наблюдения, и все они уезжают в браузер при каждом обновлении —
 * почти три тысячи объектов на ответ. При этом график в карточке
 * высотой шестьдесят восемь пикселей и шириной около трёхсот:
 * сорок восемь точек на нём ложатся с шагом в шесть пикселей,
 * то есть половина из них неразличима физически.
 *
 * Мы платим трафиком и разбором JSON за подробность, которую
 * невозможно увидеть.
 *
 * Прореживать надо с оговоркой. Наивный способ — брать каждую N-ю
 * точку — теряет ровно то, ради чего график и смотрят: одиночный
 * выброс, то есть пик или провал, с большой вероятностью окажется
 * между взятыми точками и исчезнет. Для радара это недопустимо:
 * пиковая кратность — главное число на карточке, и график, где пика
 * не видно, ей противоречит.
 *
 * Поэтому крайние точки и экстремумы сохраняются всегда.
 */

export interface SeriesPoint {
  /** Время наблюдения. */
  t: number;
  /** Цена. */
  p: number | null;
  /** Капитализация. */
  m: number | null;
}

/** Значение, по которому строится линия. Совпадает с логикой отрисовки. */
function valueOf(pt: SeriesPoint): number | null {
  const v = pt.m ?? pt.p;
  return v != null && Number.isFinite(v) && v > 0 ? v : null;
}

/**
 * Оставить не больше `max` точек, сохранив форму кривой.
 *
 * Гарантии: первая и последняя точки остаются всегда; точки
 * с наибольшим и наименьшим значением остаются всегда; порядок
 * по времени сохраняется.
 */
export function downsample(points: SeriesPoint[], max = 20): SeriesPoint[] {
  if (!Array.isArray(points)) return [];
  if (points.length <= max) return points;
  if (max < 2) return points.slice(-1);

  const n = points.length;

  // Индексы, которые обязаны попасть в результат.
  const keep = new Set<number>([0, n - 1]);

  let minIdx = -1;
  let maxIdx = -1;
  let minVal = Number.POSITIVE_INFINITY;
  let maxVal = Number.NEGATIVE_INFINITY;

  for (let i = 0; i < n; i++) {
    const v = valueOf(points[i]!);
    if (v == null) continue;
    if (v < minVal) {
      minVal = v;
      minIdx = i;
    }
    if (v > maxVal) {
      maxVal = v;
      maxIdx = i;
    }
  }

  if (minIdx >= 0) keep.add(minIdx);
  if (maxIdx >= 0) keep.add(maxIdx);

  // Остальное добираем равномерно по времени. Шаг считается от числа
  // свободных мест, а не от исходной длины: иначе обязательные точки
  // вытесняют равномерные и в середине графика образуется провал.
  const free = Math.max(0, max - keep.size);
  if (free > 0) {
    const step = (n - 1) / (free + 1);
    for (let k = 1; k <= free; k++) {
      keep.add(Math.round(k * step));
    }
  }

  return [...keep].sort((a, b) => a - b).map((i) => points[i]!);
}

/**
 * Сколько точек отдавать под график заданной ширины.
 *
 * Меньше двух точек рисовать нечего, больше одной на два пикселя —
 * не видно. Значение округляется вниз до разумного предела: точность
 * сверх различимой глазом стоит трафика и не даёт ничего.
 */
export function pointsForWidth(widthPx: number): number {
  return Math.max(2, Math.min(48, Math.floor(widthPx / 12)));
}
