/**
 * Состояние пула: жив он или из него вышли.
 *
 * Отдельно от проверки контракта, потому что отвечает на другой вопрос
 * и в другой момент. Проверка контракта спрашивает «можно ли продать
 * в принципе» и делается один раз: свойства контракта не меняются.
 * Здесь вопрос «есть ли кому продать прямо сейчас», и он требует
 * ответа при каждом обновлении.
 *
 * Разница видна на конкретном случае. Токен находится с пулом
 * на пятьдесят тысяч, проходит все проверки и попадает в ленту
 * законно. Через час создатель забирает ликвидность, в пуле остаётся
 * меньше доллара, а в карточке продолжают висеть оборот в семьсот
 * тысяч и рост в сто процентов — числа за сутки, накопленные до
 * обвала. Формально всё верно, фактически это приглашение купить
 * то, из чего уже вышли.
 *
 * Отсюда два правила ниже. Первое ловит абсолютную величину: пул
 * меньше порога непригоден независимо от истории. Второе ловит
 * обвал: пул, потерявший почти всю глубину, опасен даже если
 * формально ещё выше порога.
 *
 * Оба считаются по числам, которые у нас уже есть, — обращений
 * к внешним источникам не требуется, и потому проверку можно
 * выполнять при каждом обновлении цены, а не раз в сутки.
 */

export interface PoolSnapshot {
  /** Ликвидность сейчас. null означает «не знаем», а не «нет». */
  liquidityUsd: number | null;
  /** Ликвидность в момент обнаружения — база для сравнения. */
  liquidityAtSignalUsd: number | null;
  /** Оборот за сутки. */
  volume24hUsd: number | null;
}

export interface PoolHealth {
  /** Пул непригоден: показывать токен нельзя. */
  isDead: boolean;
  /** Ликвидность обвалилась относительно момента находки. */
  isDrained: boolean;
  /** Оборот несопоставим с глубиной пула. */
  isImplausibleVolume: boolean;
  /** Человеческое объяснение. null, если всё в порядке. */
  reason: string | null;
  /** Машинный код для фильтрации и статистики. */
  code: 'LOW_LIQUIDITY' | 'DRAINED_POOL' | 'SUSPICIOUS_VOLUME' | null;
}

/**
 * Минимальная глубина, при которой выход возможен.
 *
 * Двадцать пять тысяч: при меньшей продажа на тысячу двигает цену
 * на десятки процентов, и «продать можно» становится формальностью.
 */
export const MIN_POOL_LIQUIDITY_USD = 25_000;

/**
 * Доля от исходной ликвидности, ниже которой пул считается покинутым.
 *
 * Двадцать процентов, а не половина. Колебания глубины пула на треть
 * бывают при обычной торговле, и объявлять их бегством значило бы
 * прятать живые токены. Потеря четырёх пятых обычной торговлей
 * не объясняется.
 */
export const DRAIN_RATIO = 0.2;

/**
 * Отношение оборота к ликвидности, выше которого числа несовместимы.
 *
 * Тысяча — заведомо абсурдная величина, взятая с запасом. Обычный
 * порог подозрительности втрое ниже, но здесь речь не о подозрении,
 * а о невозможности: оборот в тысячу раз больше глубины пула означает,
 * что одно из двух чисел относится к другому моменту времени.
 */
export const ABSURD_VOLUME_RATIO = 1000;

export function checkPoolHealth(s: PoolSnapshot): PoolHealth {
  const ok: PoolHealth = {
    isDead: false,
    isDrained: false,
    isImplausibleVolume: false,
    reason: null,
    code: null,
  };

  const liq = s.liquidityUsd;

  // Неизвестная ликвидность — не повод объявлять пул мёртвым.
  // Это отсутствие сведений, и обращаться с ним надо как с таковым.
  if (liq == null || !Number.isFinite(liq)) return ok;

  // ─── Абсолютная величина ──────────────────────────────────────────
  //
  // Ноль сюда попадает и обрабатывается наравне с остальными: именно
  // осушенный пул и есть тот случай, ради которого правило написано.
  if (liq < MIN_POOL_LIQUIDITY_USD) {
    return {
      isDead: true,
      isDrained: true,
      isImplausibleVolume: false,
      reason:
        liq < 1
          ? 'Ликвидность пула исчерпана — продать некому'
          : `Ликвидность $${Math.round(liq).toLocaleString('ru-RU')} — выйти без обвала нельзя`,
      code: 'LOW_LIQUIDITY',
    };
  }

  // ─── Обвал относительно находки ───────────────────────────────────
  const base = s.liquidityAtSignalUsd;
  if (base != null && Number.isFinite(base) && base > 0 && liq < base * DRAIN_RATIO) {
    const lostPct = Math.round((1 - liq / base) * 100);
    return {
      isDead: true,
      isDrained: true,
      isImplausibleVolume: false,
      reason: `Из пула вывели ${lostPct}% ликвидности с момента находки`,
      code: 'DRAINED_POOL',
    };
  }

  // ─── Несовместимость оборота и глубины ────────────────────────────
  const vol = s.volume24hUsd;
  if (vol != null && Number.isFinite(vol) && vol > 0 && liq > 0) {
    const ratio = vol / liq;
    if (ratio > ABSURD_VOLUME_RATIO) {
      return {
        isDead: true,
        isDrained: false,
        isImplausibleVolume: true,
        reason:
          `Оборот $${Math.round(vol).toLocaleString('ru-RU')} при ликвидности ` +
          `$${Math.round(liq).toLocaleString('ru-RU')} — числа относятся к разным моментам, ` +
          'скорее всего пул уже покинут',
        code: 'SUSPICIOUS_VOLUME',
      };
    }
  }

  return ok;
}
