/**
 * Под какой базой живёт маршрут.
 *
 * В проекте две: `/api/v1` для торгового интерфейса и `/api` для
 * доступа и оплаты. Разделение осмысленное — права и тарифы
 * не должны менять адрес при каждой смене версии торгового API, —
 * но платится за него тем, что выбрать базу можно неправильно.
 *
 * Неправильно выбранная база даёт 404, и это худший вид ошибки:
 * страница тарифов гасит ошибку каждого необязательного запроса,
 * поэтому три подряд 404 выглядели не как поломка, а как пустой
 * каталог. Один раз так и случилось.
 *
 * Поэтому соответствие «маршрут → база» записано здесь и проверяется
 * тестом, а не держится на внимательности при написании страницы.
 */

export type ApiBaseKind = 'v1' | 'root';

/**
 * Префиксы маршрутов, живущих вне версии торгового API.
 *
 * Список сверен с регистрацией в `apps/api/src/server.ts`: под `/api`
 * зарегистрированы ровно `accessRoutes`, `paymentRoutes`
 * и `webhookRoutes`. Всё остальное, включая `authRoutes`, —
 * под `/api/v1`.
 *
 * Вход и регистрация сюда не входят, хотя по смыслу и просятся:
 * они про то, кто пользователь, а не про версию торгового API.
 * Но таблица описывает не смысл, а факт, и разойтись с фактом
 * ей нельзя — иначе она перестаёт быть защитой и становится
 * вторым источником ошибок. Один раз так и вышло: `/auth/` попал
 * сюда по смыслу, и вход сломался бы на первом же запросе.
 *
 * Всё, что не совпало, — версионированное. Умолчание в эту сторону
 * выбрано потому, что таких маршрутов подавляющее большинство,
 * и новый торговый маршрут не требует правки этого списка.
 */
export const ROOT_API_PREFIXES: readonly string[] = ['/access/', '/payments/', '/webhooks/'];

/**
 * Какая база нужна маршруту.
 *
 * Путь берётся без строки запроса: база определяется маршрутом,
 * а не его параметрами.
 */
export function apiBaseFor(path: string): ApiBaseKind {
  const clean = path.split('?')[0] ?? path;

  // Точное совпадение с префиксом без хвоста тоже считается:
  // `/payments` — это тот же модуль, что и `/payments/status`.
  const matches = ROOT_API_PREFIXES.some(
    (prefix) => clean.startsWith(prefix) || clean === prefix.slice(0, -1),
  );

  return matches ? 'root' : 'v1';
}
