import type { PlanCode } from './entitlements.js';

/**
 * Правила входа, регистрации и первого перехода.
 *
 * Сервер остаётся единственным авторитетом: всё, что здесь есть,
 * повторяется на нём. Смысл этих функций в другом — дать одинаковый
 * ответ на клиенте и на сервере. Разошедшиеся правила проявляются
 * как форма, которая пропускает значение, и сервер, который его
 * отвергает: человек видит отказ там, где интерфейс только что
 * сказал «всё хорошо».
 */

// ─────────────────────────────── Почта ──────────────────────────────────────

/**
 * Приведение адреса к сравнимому виду.
 *
 * `User@Example.com`, ` user@example.com ` и `user@example.com` —
 * один и тот же почтовый ящик. Домен по стандарту нечувствителен
 * к регистру, локальная часть формально чувствительна, но ни один
 * массовый провайдер этим не пользуется, а вот люди путаются
 * постоянно.
 *
 * Нормализация обязана происходить до поиска и до записи. Иначе
 * человек регистрируется как `User@…`, входит как `user@…` и получает
 * «неверный email или пароль» при верном пароле.
 */
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

/** Похоже ли на адрес. Строгая проверка — на сервере и у провайдера. */
export function emailLooksValid(email: string): boolean {
  const value = normalizeEmail(email);

  // Ровно одна собака, что-то до неё, домен с точкой после.
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value)) return false;

  // Предел RFC. Длиннее не бывает, а вот попытки переполнить поле
  // длинной строкой — бывают.
  return value.length <= 254;
}

// ─────────────────────────────── Пароль ─────────────────────────────────────

/**
 * Нижняя граница длины.
 *
 * Десять знаков — не идеал, а то, что уже действует на сервере.
 * Менять её здесь значило бы разойтись с ним.
 */
export const PASSWORD_MIN = 10;

/**
 * Верхняя граница.
 *
 * Не про надёжность, а про стоимость: argon2 считает хэш от всей
 * строки, и мегабайтный «пароль» превращает форму входа в способ
 * занять процессор сервера.
 */
export const PASSWORD_MAX = 200;

export type PasswordIssue = 'EMPTY' | 'TOO_SHORT' | 'TOO_LONG' | 'WHITESPACE_ONLY';

/** Что не так с паролем. `null` — всё в порядке. */
export function passwordIssue(password: string): PasswordIssue | null {
  if (password.length === 0) return 'EMPTY';

  // Пробелы — законные знаки внутри пароля, но пароль целиком
  // из пробелов человек не наберёт повторно никогда.
  if (password.trim().length === 0) return 'WHITESPACE_ONLY';

  if (password.length < PASSWORD_MIN) return 'TOO_SHORT';
  if (password.length > PASSWORD_MAX) return 'TOO_LONG';

  return null;
}

export const PASSWORD_HINT = `Не короче ${PASSWORD_MIN} знаков. Пробелы допустимы, но не весь пароль из них.`;

// ──────────────────────────────── 2FA ───────────────────────────────────────

export type TotpIssue = 'EMPTY' | 'NOT_SIX_DIGITS';

/**
 * Код подтверждения — ровно шесть цифр.
 *
 * Не «шесть символов»: буквы в поле означают, что человек вставил
 * не то, и сказать ему это надо до отправки, а не после отказа
 * сервера с общей формулировкой.
 */
export function totpIssue(code: string): TotpIssue | null {
  const value = code.trim();

  if (value.length === 0) return 'EMPTY';
  return /^\d{6}$/.test(value) ? null : 'NOT_SIX_DIGITS';
}

// ───────────────── Куда ведёт логотип ───────────────────────────────────────

/**
 * Состояние доступа, от которого зависит первый переход.
 *
 * Ровно те поля, что влияют на ответ. Роль сюда не входит: служебный
 * доступ приходит с сервера отдельным полем, и выводить его из роли
 * в браузере значит завести второй источник прав.
 */
export interface LogoDestinationInput {
  /** Идёт первая загрузка прав: ответа сервера ещё не было. */
  loading: boolean;
  /** Сервер сказал, что человек не авторизован. */
  anonymous: boolean;
  /** В браузере есть токен сессии. */
  hasSession: boolean;
  plan: PlanCode | null;
  /** Доступ выдан ролью. Решает сервер. */
  serviceAccess: boolean;
}

/**
 * Куда ведёт логотип.
 *
 * ─── Почему функция, а не тернарник в разметке ──────────────────────
 *
 * Состояний пять, и различаются они не оформлением, а смыслом.
 * Разложенные по разметке, они проверяются только руками — а ошибка
 * здесь отправляет человека на страницу, которой он не ждал, и
 * выглядит как поломка навигации.
 *
 * ─── Про загрузку ───────────────────────────────────────────────────
 *
 * Пока ответа нет, адрес не меняется. Подставить `/plans` заранее
 * значит увести оплатившего человека на витрину тарифов; подставить
 * `/terminal` — упереть гостя в сторожа маршрута. Приветственная
 * страница безопасна для всех и никого не удивляет.
 */
export function logoDestination(input: LogoDestinationInput): string {
  // Сессии нет вовсе — гость.
  if (!input.hasSession && input.anonymous) return '/';

  // Ответа ещё не было: ничего не утверждаем.
  if (input.loading || input.plan == null) return '/';

  // Сервер отказал: токен есть, но он не признан.
  if (input.anonymous) return '/';

  /*
   * Служебный доступ раньше плана.
   *
   * У администратора план может быть каким угодно, включая
   * истёкший, а возможности при этом полные. Проверь мы сначала
   * план — и он попадал бы на витрину тарифов.
   */
  if (input.serviceAccess) return '/terminal';

  // Доступа нет: единственное осмысленное продолжение — выбрать план.
  if (input.plan === 'EXPIRED') return '/plans';

  return '/terminal';
}

// ─────────────── Гостевые кнопки в шапке ────────────────────────────────────

export interface GuestActionsInput {
  /** Текущий путь без параметров. */
  pathname: string;
  /** Значение параметра `mode`. */
  mode: string | null;
  /** В браузере есть сессия. */
  hasSession: boolean;
}

export interface GuestActions {
  showLogin: boolean;
  showRegister: boolean;
}

/**
 * Какие гостевые кнопки показывать в шапке.
 *
 * Кнопка, дублирующая уже открытую форму, — не подсказка, а шум:
 * на странице регистрации предлагать регистрацию бессмысленно,
 * и нажатие на неё ничего не меняет.
 *
 * Режим читается из параметра `mode`, а не из пути: вход
 * и регистрация живут на одном маршруте и различаются только им.
 */
export function guestHeaderActions(input: GuestActionsInput): GuestActions {
  // Появилась сессия — гостевых кнопок нет вовсе.
  if (input.hasSession) return { showLogin: false, showRegister: false };

  if (input.pathname !== '/login') return { showLogin: true, showRegister: true };

  return input.mode === 'register'
    ? { showLogin: true, showRegister: false }
    : { showLogin: false, showRegister: true };
}
