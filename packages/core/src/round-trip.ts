/**
 * Трактовка замера «купить и сразу продать обратно».
 *
 * Это самая сильная из доступных проверок, и стоит объяснить почему.
 *
 * Все остальные проверки — косвенные. Список безопасности отвечает
 * «мы не нашли признаков ловушки»: он может не знать про эту конкретную,
 * может ошибаться, может отставать. Счётчики сделок отвечают «за сутки
 * никто не продал» — но, может, просто не хотели. Сверка источников
 * отвечает «числа сходятся» — числа могут сходиться и у ловушки.
 *
 * Замер круга отвечает на сам вопрос: сколько вернётся, если выйти
 * прямо сейчас. Не признак ловушки, а её последствие, измеренное
 * заранее и в деньгах.
 *
 * Цена этой точности — два запроса к агрегатору на токен, поэтому
 * применять её ко всему подряд нельзя.
 */

export interface RoundTripInput {
  canBuy: boolean;
  canSell: boolean;
  /** Доля вложенного, возвращающаяся при немедленном выходе. */
  returnRatio: number | null;
}

export type RoundTripVerdict = 'BLOCK' | 'WARN' | 'OK' | 'UNKNOWN';

export interface RoundTripDecision {
  verdict: RoundTripVerdict;
  reason: string;
  /** Потери на круг в процентах, если их удалось измерить. */
  lossPct: number | null;
}

/**
 * Ниже этого возврата токен считается ловушкой.
 *
 * Половина вложенного — это уже не «дорогой обмен», а изъятие. Два
 * честных обмена на тонком пуле обходятся в единицы процентов,
 * на очень тонком — в десятки, но не в разы.
 */
export const TRAP_RETURN_RATIO = 0.5;

/**
 * Ниже этого — предупреждение.
 *
 * Восемьдесят пять процентов означает пятнадцать процентов потерь
 * на вход и выход. Это много, но бывает у честных токенов
 * с маленьким пулом, и запрещать такое было бы перебором.
 */
export const COSTLY_RETURN_RATIO = 0.85;

export function judgeRoundTrip(r: RoundTripInput): RoundTripDecision {
  if (!r.canBuy) {
    /*
     * Замер не начался — о продаже он не сказал ничего.
     *
     * Версия 9 делала здесь BLOCK и тем самым объявляла BRETT и другие
     * крупные рынки ловушками только потому, что конкретный агрегатор
     * не поддержал вход через выбранный нативный актив. Отсутствие
     * маршрута у одного провайдера может означать сеть, адрес нативного
     * токена, лимит API или неподдерживаемый пул. Это наша неспособность
     * выполнить пробу, а не доказанная невозможность выйти.
     */
    return {
      verdict: 'UNKNOWN',
      reason: 'Агрегатор не построил маршрут на покупку — замер выхода не выполнен',
      lossPct: null,
    };
  }

  if (!r.canSell) {
    // Купить можно, продать нельзя. Это определение ловушки, и здесь
    // не нужны ни списки, ни статистика: проверка выполнена напрямую.
    return {
      verdict: 'BLOCK',
      reason: 'Купить можно, продать нельзя — маршрут наружу не строится',
      lossPct: null,
    };
  }

  if (r.returnRatio == null || !Number.isFinite(r.returnRatio) || r.returnRatio <= 0) {
    return {
      verdict: 'UNKNOWN',
      reason: 'Замер не удался — проверить возможность выхода не получилось',
      lossPct: null,
    };
  }

  const lossPct = (1 - r.returnRatio) * 100;

  if (r.returnRatio < TRAP_RETURN_RATIO) {
    return {
      verdict: 'BLOCK',
      reason:
        `На круге покупка-продажа теряется ${lossPct.toFixed(0)}% — ` +
        'это изъятие, а не стоимость обмена',
      lossPct,
    };
  }

  if (r.returnRatio < COSTLY_RETURN_RATIO) {
    return {
      verdict: 'WARN',
      reason: `Вход и выход обойдутся примерно в ${lossPct.toFixed(0)}% — пул тонкий`,
      lossPct,
    };
  }

  // Возврат выше единицы бывает: цена сдвинулась между двумя запросами.
  // Это не прибыль и обещать её нельзя, поэтому в тексте её нет.
  return {
    verdict: 'OK',
    reason:
      r.returnRatio >= 1
        ? 'Выход возможен, потери на обмене в пределах погрешности'
        : `Выход возможен, потери на круге около ${lossPct.toFixed(1)}%`,
    lossPct: Math.max(0, lossPct),
  };
}
