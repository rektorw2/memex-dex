#!/bin/sh
set -eu

# Схема приводится в порядок до старта сервера, иначе Prisma Client
# пойдёт за колонками, которых в базе нет.
#
# Это не «применить всё, что лежит в prisma/migrations». Загрузчик
# знает конечный список миграций (KNOWN_MIGRATIONS) и отказывается
# работать, если в репозитории появилась незнакомая ему. Добавили
# миграцию — впишите её в список, иначе деплой остановится.
#
# set -eu: отказ загрузчика обязан останавливать запуск. Поднятый
# сервер на несошедшейся схеме — это пятисотые на боевых маршрутах.
node apps/api/dist/repair-production-schema.js
exec node apps/api/dist/server.js
