/**
 * Адрес тестовой базы и защита от боевой.
 *
 * Один источник правды для двух мест: глобальной подготовки, которая
 * накатывает схему, и setup-файла, который подставляет адрес рабочим
 * процессам. Две копии проверки однажды разошлись бы, и разошлись бы
 * именно в ту сторону, где защита слабее.
 */

/**
 * Проверенный адрес тестовой базы.
 *
 * Бросает исключение, если адрес не задан или похож на боевой.
 * Строка подключения наружу не выводится ни в одном сообщении:
 * в ней пароль.
 */
export function requireE2eDatabaseUrl(): string {
  const url = process.env.E2E_DATABASE_URL;

  if (!url) {
    throw new Error(
      'Сквозной стенд требует E2E_DATABASE_URL — адрес пустой тестовой базы PostgreSQL. ' +
        'Пример: E2E_DATABASE_URL=postgresql://memex:memex@localhost:5432/memex_e2e',
    );
  }

  /*
   * Имя базы обязано содержать `test` или `e2e`.
   *
   * Стенд очищает данные между сценариями. Опечатка в адресе здесь
   * означала бы не упавший тест, а стёртую базу, поэтому правило
   * намеренно грубое: тонкий разбор строки подключения ошибся бы
   * ровно один раз, и этого раза хватило бы.
   */
  const database = url.split('/').pop()?.split('?')[0] ?? '';

  if (!/test|e2e/i.test(database)) {
    throw new Error(
      `Имя базы «${database}» не содержит test или e2e. ` +
        'Сквозной стенд удаляет данные между сценариями и на такой базе не запускается.',
    );
  }

  /*
   * Управляемые хостинги отвергаются по имени.
   *
   * У боевой базы может оказаться подходящее имя — например
   * `memex_test` на стенде, который на самом деле общий. Признак
   * хостинга не зависит от имени базы и ловит этот случай.
   */
  if (/neon\.tech|render\.com|amazonaws\.com|rds\.|supabase\.|azure\.|gcp\.|prod/i.test(url)) {
    throw new Error(
      'Адрес указывает на управляемый хостинг или содержит признак production. ' +
        'Сквозной стенд на такой базе не запускается.',
    );
  }

  return url;
}

/**
 * Переменные окружения для Prisma CLI.
 *
 * Адрес передаётся сразу под двумя именами: `DATABASE_URL` читает
 * datasource, `DIRECT_DATABASE_URL` — конфигурации, где миграции
 * идут в обход пула. Одно из двух имён рано или поздно окажется
 * нужным, и лучше это не выяснять посреди прогона.
 */
export function prismaEnv(url: string): NodeJS.ProcessEnv {
  return {
    ...process.env,
    DATABASE_URL: url,
    DIRECT_DATABASE_URL: url,
  };
}
