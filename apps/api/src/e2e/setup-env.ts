import { requireE2eDatabaseUrl } from './e2e-database.js';

/**
 * Подготовка окружения рабочего процесса. Выполняется до загрузки тестов.
 *
 * Единственная задача — подставить адрес тестовой базы в `DATABASE_URL`
 * раньше, чем кто-либо создаст клиента Prisma. Это возможно только в
 * setup-файле: внутри теста импорты выполняются до любого кода модуля,
 * и присваивание опоздало бы.
 *
 * Схему здесь никто не накатывает — это делает `global-setup.ts` один
 * раз на весь прогон настоящей командой `prisma migrate deploy`.
 *
 * Почему это не подмена. Клиент в `lib/prisma.ts` создаётся лениво и
 * читает `DATABASE_URL` в момент первого запроса. Стенд не подменяет ни
 * клиента, ни модуль — он лишь указывает, к какой базе подключаться.
 * Дальше работает тот же код, что и в production.
 */

const url = requireE2eDatabaseUrl();

process.env.DATABASE_URL = url;
process.env.DIRECT_DATABASE_URL = url;
