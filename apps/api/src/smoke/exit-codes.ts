/**
 * Коды выхода smoke-проверок.
 *
 * Разные причины отказа обязаны различаться числом. Один общий код
 * ошибки заставляет читать вывод глазами, а вывод у smoke намеренно
 * скупой — в нём нет ни payload, ни ключей. Без различимых кодов
 * такую проверку нельзя поставить в конвейер: «упало» не отвечает
 * на вопрос, чинить сеть, ключи или наш разбор ответа.
 */
export const SMOKE_EXIT = {
  ok: 0,
  /** Не заданы ключи или переменные запуска. Чинится настройкой. */
  config: 2,
  /** До провайдера не достучались. Чинится сетью или ожиданием. */
  network: 3,
  /** Ключи есть, но вход отклонён. Чинится ключами. */
  auth: 4,
  /** Ответ пришёл, но не той формы, которую мы разбираем. */
  contract: 5,
  /** Уложиться в отведённое время не удалось. */
  timeout: 6,
  /** Схема базы отстала от кода. */
  schema: 7,
} as const;

export type SmokeExit = (typeof SMOKE_EXIT)[keyof typeof SMOKE_EXIT];

/** Сообщение об отсутствии сети. Формулировка постоянная. */
export const NETWORK_UNAVAILABLE = 'Live verification not performed: OKX_NETWORK_UNAVAILABLE.';

/**
 * Сокращение адреса для вывода.
 *
 * Полный адрес кошелька в журнале сборки — это указание на то, за кем
 * мы следим. Для проверки связи достаточно знать, что адрес непустой
 * и тот самый.
 */
export function maskAddress(address: string): string {
  if (address.length <= 10) return '…';
  return `${address.slice(0, 4)}…${address.slice(-4)}`;
}
