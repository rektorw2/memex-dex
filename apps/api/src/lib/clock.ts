/**
 * Серверное время.
 *
 * Единственное место, откуда его берут решения о доступе. Причина
 * не в удобстве тестов, хотя они тоже: время, разбросанное по коду
 * вызовами `new Date()`, невозможно ни подделать целиком, ни
 * проверить на границе.
 *
 * А границу проверять надо. Пробный период кончается через сто
 * двадцать часов, и разница между «за миллисекунду до» и «ровно в»
 * — это разница между открытым и закрытым радаром. Ждать пять суток
 * ради такой проверки нельзя, а проверять «примерно потом» бесполезно:
 * ошибка на единицу живёт именно в этой миллисекунде.
 *
 * Часы браузера сюда не попадают никогда и никаким путём. Перевести
 * время на своём компьютере — самый простой способ продлить себе
 * бесплатный доступ, и единственная защита от этого в том, что мы
 * его не спрашиваем.
 */
export function serverNow(): Date {
  return new Date();
}

/** То же в миллисекундах. Отдельно, чтобы не плодить `.getTime()`. */
export function serverNowMs(): number {
  return serverNow().getTime();
}
