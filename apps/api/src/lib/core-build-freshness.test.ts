import { describe, expect, it } from 'vitest';
import { coreBuildFreshness } from './core-build-freshness.js';

/**
 * Сборка ядра не отстаёт от его исходников.
 *
 * Тест стоит в обычном наборе намеренно. API импортирует ядро как
 * собранный пакет: пока `packages/core/dist` не обновлён, все тесты
 * API проверяют прошлую версию правил. Один раз это уже дало 74/75,
 * и после пересборки — 75/75; но точно так же оно способно дать
 * зелёный прогон на коде, которого больше нет.
 *
 * Поэтому проверка отдельная и с внятным сообщением: иначе причина
 * прячется за случайным упавшим тестом где-то в середине набора,
 * и на её поиск уходит прогон целиком.
 */

describe('сборка @memex/core актуальна', () => {
  it('dist не старше src', () => {
    const verdict = coreBuildFreshness();

    expect(verdict.fresh, verdict.reason).toBe(true);
  });

  it('причина отставания называет команду, которую нужно выполнить', () => {
    /*
     * Проверка самого сообщения, а не состояния. Сообщение вида
     * «сборка устарела» отправляет искать, что с этим делать;
     * команда в тексте закрывает вопрос сразу.
     */
    const verdict = coreBuildFreshness();

    if (verdict.fresh) {
      // Сборка свежая — проверяем текст на искусственно устаревшем
      // состоянии нельзя, но контракт всё равно должен быть виден.
      expect(verdict.reason).toBe('');
      return;
    }
    expect(verdict.reason).toContain('npm run build -w @memex/core');
  });
});
