import { readdirSync } from 'node:fs';

/**
 * Имена миграций, лежащих в репозитории.
 *
 * Вынесено из загрузчика, потому что читателей стало двое: сам
 * загрузчик и служба, отвечающая на вопрос «применена ли схема
 * целиком». Две копии этой функции разошлись бы на первой же правке
 * пути, и одна из них начала бы молча возвращать `null`.
 *
 * `null` означает нечитаемый каталог и трактуется как отказ, а не как
 * пропуск проверки: ошибка чтения не должна снимать защиту, ради
 * которой проверка заведена.
 */
export function migrationsOnDisk(): string[] | null {
  /*
   * Путь считается от самого файла, а не от рабочего каталога.
   * Приложение стартует из `/app`, но полагаться на это незачем.
   * Из `apps/api/dist/lib/` и из `apps/api/src/lib/` глубина
   * одинакова, поэтому путь работает и в контейнере, и под tsx.
   */
  const dir = new URL('../../../../prisma/migrations', import.meta.url);

  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name);
  } catch {
    return null;
  }
}
