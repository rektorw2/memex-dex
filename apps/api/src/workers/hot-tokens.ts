/**
 * Токены, на которые кто-то смотрит прямо сейчас.
 *
 * Один список на все фоновые работы. Свечам, ценам и проверке нужен
 * ответ на один и тот же вопрос — «кто ждёт», — и три отдельных
 * множества разошлись бы при первой же правке: открытый токен получал
 * бы свежие свечи, но вчерашнюю цену.
 *
 * Почему это вообще нужно. Обычный обход идёт по обороту и берёт
 * первые несколько сотен. Токен за их пределами не обновится никогда,
 * а открывают чаще всего именно такой: пришли по ссылке, из поиска,
 * из радара.
 *
 * Ограничений два, и оба обязательны.
 *
 * Размер — иначе список раздует кто угодно, открывая карточки
 * подряд, и «горячим» станет всё, то есть ничего.
 *
 * Срок — уйти со страницы браузер нам не сообщает, и без него токен
 * оставался бы горячим вечно. Пока человек смотрит, клиент опрашивает
 * сервер и продлевает метку сам; перестал — метка гаснет за минуту.
 */

/** Сколько токенов держим горячими. */
export const HOT_LIMIT = 50;

/**
 * Сколько метка живёт без обновления.
 *
 * Заметно больше периода опроса клиента, чтобы одна потерянная
 * сетевая попытка не выбрасывала токен из горячих, и заметно меньше
 * времени, которое человек проводит на странице.
 */
export const HOT_TTL_MS = 90_000;

/** id → когда последний раз спрашивали. */
const lastSeen = new Map<string, number>();

/**
 * Отметить, что токен кому-то нужен.
 *
 * Вызывается из маршрутов чтения. Повторный вызов продлевает метку
 * и двигает токен в конец: Map сохраняет порядок вставки, и удалять
 * при переполнении надо самый давний.
 */
export function markHot(tokenId: string, now: number = Date.now()): void {
  lastSeen.delete(tokenId);
  lastSeen.set(tokenId, now);

  while (lastSeen.size > HOT_LIMIT) {
    const oldest = lastSeen.keys().next().value as string | undefined;
    if (oldest == null) break;
    lastSeen.delete(oldest);
  }
}

/** Протухшие метки убираются лениво: отдельный таймер здесь лишний. */
function sweep(now: number, ttlMs: number): void {
  for (const [id, at] of lastSeen) {
    // Map отдаёт ключи в порядке вставки, поэтому первый непротухший
    // означает, что дальше все свежие.
    if (now - at <= ttlMs) break;
    lastSeen.delete(id);
  }
}

/** Горячие токены, от самого свежего запроса к самому давнему. */
export function hotTokens(now: number = Date.now(), ttlMs: number = HOT_TTL_MS): string[] {
  sweep(now, ttlMs);
  return [...lastSeen.keys()].reverse();
}

export function isHot(
  tokenId: string,
  now: number = Date.now(),
  ttlMs: number = HOT_TTL_MS,
): boolean {
  const at = lastSeen.get(tokenId);
  return at != null && now - at <= ttlMs;
}

export function hotCount(now: number = Date.now(), ttlMs: number = HOT_TTL_MS): number {
  sweep(now, ttlMs);
  return lastSeen.size;
}

// ──────────────────────── Отметка из серверного списка ──────────────────────

/**
 * Сколько токенов одного ответа считаются видимыми.
 *
 * ─── Почему помечаем ответ сервера, а не присланный клиентом список ──
 *
 * Рассматривались два варианта. Отдельный маршрут регистрации видимых
 * идентификаторов честнее описывает намерение, но стоит лишнего
 * запроса на каждую прокрутку и требует проверять каждый присланный
 * идентификатор: существует ли токен, не скрыт ли он, не подсунули ли
 * тысячу чужих.
 *
 * Помечать то, что сервер сам только что вернул, дешевле и безопаснее.
 * Лишних запросов ноль. Идентификаторы наши собственные, поэтому
 * несуществующих и скрытых среди них не бывает по построению —
 * проверять нечего.
 *
 * ─── Почему не весь список ───────────────────────────────────────────
 *
 * Ответ отдаёт до двухсот токенов, а на экране помещается десяток.
 * Пометить все двести значит вытеснить из горячих открытые карточки
 * и объявить горячим полкаталога. Берётся начало отсортированной
 * выдачи: это и есть то, что человек видит, не прокручивая.
 */
export const LIST_HOT_LIMIT = 12;

/**
 * Сколько отметок из списков разрешено в минуту на весь процесс.
 *
 * Без этого предела публичный маршрут превращается в способ греть
 * каталог: достаточно перебирать страницы и сортировки, чтобы
 * заставить нас опрашивать провайдера по всей витрине каждые
 * несколько секунд.
 *
 * Предел процессный, а не на клиента: считать по клиентам значит
 * доверять его словам о том, кто он. Нам же важен итог — сколько
 * работы уходит провайдеру.
 */
export const LIST_MARK_BUDGET_PER_MIN = 120;

const BUDGET_WINDOW_MS = 60_000;

let budgetWindowStartedAt = 0;
let budgetSpent = 0;

/**
 * Отметить токены, которые сервер только что показал.
 *
 * Возвращает, сколько отметок реально поставлено: по этому числу
 * видно, упёрлись ли мы в бюджет.
 */
export function markHotFromList(ids: string[], now: number = Date.now()): number {
  if (now - budgetWindowStartedAt >= BUDGET_WINDOW_MS) {
    budgetWindowStartedAt = now;
    budgetSpent = 0;
  }

  const allowance = Math.max(0, LIST_MARK_BUDGET_PER_MIN - budgetSpent);
  if (allowance === 0) return 0;

  /*
   * Дубликаты убираются до расчёта бюджета: один и тот же токен
   * в двух списках — это одна отметка, а не две, и тратить на него
   * двойную квоту незачем.
   */
  const unique = [...new Set(ids)].slice(0, Math.min(LIST_HOT_LIMIT, allowance));

  for (const id of unique) markHot(id, now);

  budgetSpent += unique.length;
  return unique.length;
}

/** Сколько отметок из списков осталось в текущей минуте. */
export function listMarkBudgetLeft(now: number = Date.now()): number {
  if (now - budgetWindowStartedAt >= BUDGET_WINDOW_MS) return LIST_MARK_BUDGET_PER_MIN;
  return Math.max(0, LIST_MARK_BUDGET_PER_MIN - budgetSpent);
}

export function resetHotTokensForTests(): void {
  lastSeen.clear();
  budgetWindowStartedAt = 0;
  budgetSpent = 0;
}
