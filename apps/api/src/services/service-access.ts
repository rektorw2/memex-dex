import { UserRole } from '@prisma/client';
import { prisma } from '../lib/prisma.js';

/**
 * Служебный доступ администратора.
 *
 * Одно место на всё приложение. Расписанный по маршрутам, он был бы
 * не политикой, а четырнадцатью независимыми решениями, и первое же
 * забытое означало бы, что администратор не может посмотреть раздел,
 * который сам же и чинит.
 *
 * Что это такое и чем не является.
 *
 * Это обход тарифных правил: подписки, пробного периода
 * и подтверждения почты. Администратор видит продукт целиком, потому
 * что обслуживает его.
 *
 * Это не обход защиты. Вход, проверка подписи токена, ограничение
 * частоты, подпись вебхуков, идемпотентность, ключи KMS, аудит
 * и торговые risk-guards работают ровно так же. «Без ограничений»
 * сказано про тарифы, а не про безопасность и не про деньги.
 *
 * Почему роль читается из базы, а не из токена.
 *
 * Токен подписан нами и подделать его нельзя — но он снимок на момент
 * входа. Роль, снятая сегодня, осталась бы в выданном вчера токене
 * до самого истечения срока, то есть отзыв доступа не работал бы
 * тогда, когда он нужнее всего. Из тела запроса роль не читается
 * никогда и ни при каких условиях: там её пишет клиент.
 */

/**
 * Что нужно знать о пользователе для расчёта прав.
 *
 * Одно чтение вместо двух. Раньше роль и состояние почты читались
 * порознь — `hasServiceAccess` и `isEmailVerified` брали одну и ту же
 * строку двумя запросами, — и каждый вызов `/access/me` платил
 * за это лишним обращением к базе на другом континенте.
 */
export interface AccountFacts {
  serviceAccess: boolean;
  emailVerified: boolean;
}

/** Аноним ничего не может: умолчание в сторону меньших прав. */
const ANONYMOUS: AccountFacts = { serviceAccess: false, emailVerified: false };

/**
 * Роль и подтверждение почты одним запросом.
 *
 * Никаких умолчаний в сторону разрешения: несуществующий
 * пользователь и ошибка чтения одинаково закрывают доступ,
 * а не открывают его.
 */
export async function accountFacts(userId: string | null): Promise<AccountFacts> {
  if (!userId) return ANONYMOUS;

  const user = await prisma.user.findUnique({
    where: { id: userId },
    select: { role: true, emailVerifiedAt: true },
  });

  if (!user) return ANONYMOUS;

  return {
    serviceAccess: user.role === UserRole.ADMIN,
    emailVerified: user.emailVerifiedAt != null,
  };
}

/**
 * Имеет ли пользователь служебный доступ прямо сейчас.
 *
 * Оставлено для мест, где нужна только роль. Расчёт прав ходит
 * через `accountFacts`: два вопроса к одной строке — один запрос.
 */
export async function hasServiceAccess(userId: string | null): Promise<boolean> {
  return (await accountFacts(userId)).serviceAccess;
}
