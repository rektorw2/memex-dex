import { UserRole } from '@prisma/client';
import { prisma } from '../lib/prisma.js';

/**
 * Служебный доступ администратора.
 *
 * Одно место на всё приложение. Расписанный по маршрутам, он был бы
 * не политикой, а четырнадцатью независимыми решениями, и первое же
 * забытое означало бы, что администратор не может посмотреть раздел,
 * который сам же и чинит.
 *
 * Что это такое и чем не является.
 *
 * Это обход тарифных правил: подписки, пробного периода
 * и подтверждения почты. Администратор видит продукт целиком, потому
 * что обслуживает его.
 *
 * Это не обход защиты. Вход, проверка подписи токена, ограничение
 * частоты, подпись вебхуков, идемпотентность, ключи KMS, аудит
 * и торговые risk-guards работают ровно так же. «Без ограничений»
 * сказано про тарифы, а не про безопасность и не про деньги.
 *
 * Почему роль читается из базы, а не из токена.
 *
 * Токен подписан нами и подделать его нельзя — но он снимок на момент
 * входа. Роль, снятая сегодня, осталась бы в выданном вчера токене
 * до самого истечения срока, то есть отзыв доступа не работал бы
 * тогда, когда он нужнее всего. Из тела запроса роль не читается
 * никогда и ни при каких условиях: там её пишет клиент.
 */

/**
 * Имеет ли пользователь служебный доступ прямо сейчас.
 *
 * Аноним — нет. Несуществующий пользователь — нет. Никаких умолчаний
 * в сторону разрешения: ошибка чтения роли должна закрывать доступ,
 * а не открывать его.
 */
export async function hasServiceAccess(userId: string | null): Promise<boolean> {
  if (!userId) return false;

  const user = await prisma.user.findUnique({
    where: { id: userId },
    select: { role: true },
  });

  return user?.role === UserRole.ADMIN;
}
