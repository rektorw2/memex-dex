import { describe, it, expect } from 'vitest';

/**
 * Правила переходной выдачи доступа.
 *
 * Скрипт запускается по боевой базе один раз и затрагивает всех
 * пользователей разом. Ошибка в его правилах — это не сообщение
 * об ошибке, а тихо переписанные чужие подписки, и увидеть её можно
 * будет только по жалобам.
 *
 * Поэтому решение «трогать или не трогать» вынесено из скрипта
 * в отдельный модуль и проверяется здесь без базы, поштучно.
 * Ни базы, ни подключения: набор тестов, умеющий ходить в базу,
 * однажды запустят на боевой.
 */

import { decide, parseGrantArgs as parseArgs, GRANT_REFERENCE } from './legacy-grant.js';

describe('кого трогает переходная выдача', () => {
  it('выдаёт тому, у кого ничего нет', () => {
    expect(decide({ hasActiveSubscription: false, alreadyGranted: false })).toBeNull();
  });

  it('не трогает человека с действующей подпиской', () => {
    // Это может быть оплаченный план. Переписать его подарком значит
    // закрыть строку, по которой человек платил.
    expect(decide({ hasActiveSubscription: true, alreadyGranted: false })).toBe(
      'уже есть действующая подписка',
    );
  });

  it('не трогает человека с идущим пробным периодом', () => {
    // Пробный период — тоже действующая подписка. Отдельного случая
    // здесь нет намеренно: правило одно и то же.
    expect(decide({ hasActiveSubscription: true, alreadyGranted: false })).not.toBeNull();
  });

  it('не выдаёт второй раз', () => {
    expect(decide({ hasActiveSubscription: false, alreadyGranted: true })).toBe('выдача уже была');
  });

  it('повторный прогон после истечения выдачи ничего не добавляет', () => {
    // Истёкшая выдача — тоже выдача. След ищется без учёта статуса,
    // иначе скрипт раздавал бы по пять суток при каждом запуске.
    expect(decide({ hasActiveSubscription: false, alreadyGranted: true })).toBe('выдача уже была');
  });

  it('действующая подписка важнее следа выдачи', () => {
    expect(decide({ hasActiveSubscription: true, alreadyGranted: true })).toBe(
      'уже есть действующая подписка',
    );
  });
});

describe('разбор аргументов', () => {
  it('по умолчанию — пять суток, PRO и сухой прогон', () => {
    const o = parseArgs([]);

    expect(o.days).toBe(5);
    expect(o.plan).toBe('PRO');
    // Умолчание — не записывать. Скрипт, который пишет в базу
    // без флага, однажды запустят «просто посмотреть».
    expect(o.apply).toBe(false);
  });

  it('запись включается только явным флагом', () => {
    expect(parseArgs(['--apply']).apply).toBe(true);
  });

  it('принимает свой срок и свой план', () => {
    const o = parseArgs(['--apply', '--days', '14', '--plan', 'SEMI_AUTO']);

    expect(o.days).toBe(14);
    expect(o.plan).toBe('SEMI_AUTO');
  });

  it('не даёт выдать пробный период этим путём', () => {
    // У пробного периода своя проверка почты и своё правило
    // «один раз за всё время». Выдай его отсюда — оба обойдены.
    expect(() => parseArgs(['--plan', 'TRIAL'])).toThrow(/TRIAL/);
  });

  it('не даёт выдать EXPIRED', () => {
    expect(() => parseArgs(['--plan', 'EXPIRED'])).toThrow();
  });

  it('не принимает опечатку в названии плана', () => {
    expect(() => parseArgs(['--plan', 'PROO'])).toThrow();
  });

  it.each([['0'], ['-5'], ['400'], ['abc'], ['']])('не принимает срок %s', (days) => {
    expect(() => parseArgs(['--days', days])).toThrow();
  });

  it('не принимает --days без значения', () => {
    expect(() => parseArgs(['--days'])).toThrow();
  });
});

describe('метка выдачи', () => {
  it('содержит дату, чтобы следующая выдача не спуталась с этой', () => {
    // Метка без даты сделала бы вторую переходную выдачу невозможной
    // навсегда: скрипт нашёл бы старый след и прошёл мимо.
    expect(GRANT_REFERENCE).toMatch(/\d{4}-\d{2}/);
  });
});
