import type { OrderType } from '@prisma/client';

/**
 * Резервирует ли ордер средства под себя.
 *
 * Правило одно на всю систему, и живёт оно здесь, потому что участвует
 * в четырёх местах: постановка, отмена, истечение и исполнение. Стоило
 * бы разойтись хоть одному — и токены либо зависли бы заблокированными
 * навсегда, либо разблокировались дважды.
 *
 * Стоп-лосс не резервирует ничего, и это осознанно.
 *
 * Стоп существует одновременно с целью и покрывает ту же позицию: одно
 * из двух сработает, но заранее неизвестно, какое. Если бы стоп держал
 * токены, план «продать всё на 3× со стопом на −35%» требовал бы
 * заморозить двести процентов позиции, и второй ордер просто не встал бы
 * по нехватке средств — человек получил бы цель без защиты либо защиту
 * без цели, в зависимости от порядка постановки.
 *
 * Поэтому стоп — это условие, а не бронь. При срабатывании он продаёт
 * то, что фактически есть на балансе в этот момент, а не то, что было
 * при постановке.
 */
export function reservesFunds(type: OrderType): boolean {
  if (type === 'MARKET') return false;
  if (type === 'STOP_LOSS') return false;
  return true;
}
