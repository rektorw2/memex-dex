'use client';

import { useEffect, useState } from 'react';
import { safeNextPath } from '@memex/core';

/**
 * Адрес возврата из строки запроса.
 *
 * Читается в эффекте, а не через `useSearchParams`, и это не мелочь.
 * `useSearchParams` при статическом экспорте требует обёртки
 * `Suspense`, а обёртка отдаёт всю страницу заглушкой «Загружаем…»:
 * первый экран продукта приезжал пустым и оживал только после
 * загрузки скриптов. Для страницы, которая существует ровно для того,
 * чтобы объяснить незнакомому человеку, что это такое, — плохой обмен.
 *
 * Здесь обмен другой: разметка отдаётся сразу, а параметр появляется
 * после гидратации. Потерять его на эти доли секунды безопасно —
 * до загрузки скриптов кнопки всё равно не нажимаются, а проверку
 * доступа делает сервер, а не эта строка.
 */
export function useNextParam(): string | null {
  const [next, setNext] = useState<string | null>(null);

  useEffect(() => {
    // `URLSearchParams` уже раскодировал значение, и якорь внутри него
    // остаётся частью строки, а не отрезается: `#` попал в параметр
    // закодированным как `%23`, поэтому разбор запроса о него
    // не спотыкается.
    const raw = new URLSearchParams(window.location.search).get('next');
    setNext(safeNextPath(raw));
  }, []);

  return next;
}
