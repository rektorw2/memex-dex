/**
 * Доступ к Web Storage, который не роняет страницу.
 *
 * ─── Что случилось ──────────────────────────────────────────────────
 *
 * `MobileNav` читал роль так:
 *
 *     setIsAdmin(localStorage.getItem('role') === 'ADMIN');
 *
 * и падал целиком, когда хранилища не оказывалось. Комментарий рядом
 * обещал безопасность — «читаем после монтирования, localStorage
 * недоступен на сервере», — но отвечал только на один из вопросов.
 * Отсрочка до монтирования спасает от серверной отрисовки и ничего
 * не делает с остальными случаями.
 *
 * ─── Когда хранилища нет ────────────────────────────────────────────
 *
 * Их четыре, и все настоящие.
 *
 * Серверная отрисовка: `window` не существует вовсе.
 *
 * Safari в приватном режиме и браузер с запрещёнными cookie: объект
 * есть, но обращение к нему бросает `SecurityError`. Проверка
 * `typeof window !== 'undefined'` этот случай пропускает.
 *
 * Переполненная квота: чтение работает, запись бросает
 * `QuotaExceededError`.
 *
 * Среда без DOM — например, прогон тестов вне браузера: свойства
 * просто нет, и обращение даёт `Cannot read properties of undefined`.
 *
 * ─── Что здесь решено ───────────────────────────────────────────────
 *
 * Отсутствие хранилища — это отсутствие подсказки, а не особое
 * состояние пользователя. Чтение возвращает `null`: мы не знаем, что
 * там было записано. Запись молча не удаётся: значение не переживёт
 * перезагрузку, но текущий сеанс продолжает работать.
 *
 * Важно, чего здесь нет: `null` не означает «прав нет» и тем более
 * не означает «права есть». Ни одно решение о доступе на этих
 * значениях не принимается — они только помогают интерфейсу
 * не показывать то, чем всё равно нельзя воспользоваться. Настоящая
 * проверка живёт на сервере и от содержимого браузера не зависит.
 */

export type StorageKind = 'local' | 'session';

function storageOf(kind: StorageKind): Storage | null {
  // Серверная отрисовка: обращение к `window` здесь и было бы
  // той самой ошибкой гидратации.
  if (typeof window === 'undefined') return null;

  try {
    // Само обращение к свойству бросает в приватном режиме Safari,
    // поэтому оно внутри `try`, а не только вызов метода.
    return kind === 'local' ? window.localStorage : window.sessionStorage;
  } catch {
    return null;
  }
}

/** Значение или `null`, если прочитать не удалось. */
export function readStored(kind: StorageKind, key: string): string | null {
  try {
    return storageOf(kind)?.getItem(key) ?? null;
  } catch {
    return null;
  }
}

/** Записать. `false` — не удалось; вызывающий обычно продолжает работу. */
export function writeStored(kind: StorageKind, key: string, value: string): boolean {
  try {
    const storage = storageOf(kind);
    if (!storage) return false;

    storage.setItem(key, value);
    return true;
  } catch {
    // Переполненная или запрещённая квота. Значение не переживёт
    // перезагрузку, но ронять из-за этого страницу незачем.
    return false;
  }
}

/** Удалить. Отсутствие хранилища считается успехом: значения там и нет. */
export function removeStored(kind: StorageKind, key: string): void {
  try {
    storageOf(kind)?.removeItem(key);
  } catch {
    // Нечего удалять и нечем — итог тот же.
  }
}

/** Очистить хранилище целиком. Используется при выходе. */
export function clearStorage(kind: StorageKind): void {
  try {
    storageOf(kind)?.clear();
  } catch {
    // Выход не должен зависеть от того, работает ли хранилище:
    // сессию на сервере закрывает отдельный запрос.
  }
}

/** Доступно ли хранилище. Нужно там, где важно отличить «нет» от «пусто». */
export function storageAvailable(kind: StorageKind): boolean {
  return storageOf(kind) != null;
}
