'use client';

import { useEffect, useState } from 'react';
import { usePathname } from 'next/navigation';
import { readStored } from './storage';

/**
 * Роль текущего пользователя.
 *
 * ─── Что это и чем не является ──────────────────────────────────────
 *
 * Подсказка для интерфейса, а не проверка прав. Роль лежит
 * в localStorage и правится за десять секунд из консоли браузера;
 * настоящая проверка живёт на сервере, здесь мы только не показываем
 * то, чем всё равно нельзя воспользоваться.
 *
 * ─── Почему через `readStored` ──────────────────────────────────────
 *
 * Прежде здесь стояло прямое `localStorage.getItem`, и комментарий
 * рядом обещал безопасность: «читаем после монтирования, localStorage
 * недоступен на сервере». Отсрочка до монтирования закрывает только
 * серверную отрисовку. Приватный режим Safari, запрещённые cookie
 * и среда без DOM ронял тот же вызов — что и случилось с `MobileNav`,
 * повторявшим это чтение у себя.
 *
 * Недоступное хранилище означает отсутствие подсказки: роль остаётся
 * `null`, интерфейс показывает обычный вид. Не «администратор»
 * и не «прав нет» — просто неизвестно.
 */
export function useRole(): { role: string | null; isAdmin: boolean; isLeader: boolean } {
  const [role, setRole] = useState<string | null>(null);
  const pathname = usePathname();

  useEffect(() => {
    // Роль имеет смысл только при живой сессии: оставшаяся от
    // прошлого пользователя запись иначе показывала бы админские
    // пункты тому, кто уже вышел.
    const session = readStored('session', 'accessToken');

    setRole(session ? readStored('local', 'role') : null);
  }, [pathname]);

  return {
    role,
    isAdmin: role === 'ADMIN',
    // Лидер — тот, за кем повторяют. Админ входит сюда же: у него
    // те же возможности плюс управление платформой.
    isLeader: role === 'ADMIN' || role === 'TRADER',
  };
}
