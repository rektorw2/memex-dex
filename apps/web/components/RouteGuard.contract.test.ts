// @vitest-environment node
//
// Читается файл, а не отрисовывается дерево. В `jsdom`
// `import.meta.url` — адрес по http, и чтение по нему падает.

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * Как сторож запоминает адрес, куда человек шёл.
 *
 * Проверяется источник значения, а не разметка. На production
 * встречался `/memex-dex/memex-dex/agent`: сторож брал путь из
 * `window.location.pathname`, где префикс развёртывания уже есть,
 * а роутер добавлял его второй раз.
 *
 * Ошибка не косметическая. Человека, которого попросили войти,
 * возвращало на несуществующую страницу — то есть ровно тогда, когда
 * он сделал всё правильно.
 */

const source = readFileSync(new URL('./RouteGuard.tsx', import.meta.url), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\/\/.*$/gm, '');

describe('адрес возврата собирается без префикса', () => {
  it('путь берётся через снятие префикса, а не из окна напрямую', () => {
    expect(source).toContain('currentAppPath()');
  });

  it('сырой pathname из окна в next не попадает', () => {
    /*
     * Именно эта строка и давала двойной префикс. Она читается
     * естественно и потому вернётся при первой же правке, если
     * её не запретить.
     */
    expect(source).not.toMatch(/window\.location\.pathname/);
  });

  it('значение всё ещё проходит через withNext', () => {
    // `withNext` отбрасывает корень: без него вход возвращал бы
    // на первый экран, а тот снова отправлял бы на вход.
    expect(source).toContain('withNext(');
  });
});
